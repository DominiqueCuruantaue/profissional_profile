const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {validate,render} = require('./build-learning.cjs');
const original = JSON.parse(fs.readFileSync(path.join(__dirname,'../data/learning.json'),'utf8'));
const fixture = () => structuredClone(original);
validate(original);
const data = fixture();
const google = data.studies.find(study=>study.id==='google-dados');
google.chapters.push({id:'teste-capitulo',title:'Teste <capítulo>'});
data.projects.push({id:'teste-projeto',studyId:google.id,chapterId:'teste-capitulo',type:'project',title:'Teste <projeto>',description:'Descrição',learning:'Aprendizagem',skills:['SQL'],links:[]});
const html = render(data);
assert.match(html, /id="capitulo-google-dados-teste-capitulo"/);
assert.match(html, /Teste &lt;capítulo&gt;/);
assert.match(html, /Teste &lt;projeto&gt;/);
const googleHtml = html.split('id="projetos-google-dados"')[1].split('id="projetos-tecmarc"')[0];
assert.match(googleHtml,/1 projeto publicado/);
assert.match(googleHtml,/id="teste-projeto"/);
assert.match(googleHtml,/href="#formacao-google"/);
assert.equal((html.match(/id="teste-projeto"/g)||[]).length,1);
assert.doesNotMatch(render(original).split('id="projetos-moc-sql"')[1],/1 projeto publicado/);
const orphan = fixture(); orphan.projects[0].studyId='inexistente';
assert.throws(()=>validate(orphan),/Unknown study/);
const wrongChapter = fixture(); wrongChapter.projects[0].chapterId='outro-estudo';
assert.throws(()=>validate(wrongChapter),/Unknown chapter/);
const duplicate = fixture(); duplicate.projects.push(duplicate.projects[0]);
assert.throws(()=>validate(duplicate),/duplicate ID/);
const unsafe = fixture(); unsafe.projects[0].links=[{label:'Teste',url:'javascript:alert(1)'}];
assert.throws(()=>validate(unsafe),/Unsafe link/);
const missing = fixture(); missing.projects[0].links=[{label:'Teste',url:'assets/nao-existe.pdf'}];
assert.throws(()=>validate(missing),/Missing local file/);
console.log('Study/chapter links, counts, escaping and invalid data checks passed. Fixtures were not published.');
